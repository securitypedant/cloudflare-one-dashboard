#!/usr/bin/env node
// Generates worker/data/cities.ts from GeoNames cities15000 (CC BY 4.0, https://www.geonames.org/),
// used to place DEX user cities (Cloudflare's ISP IP geolocation) on the map.
// Requires `unzip` on PATH. Re-run occasionally:  node scripts/gen-cities.mjs
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fetchPinned } from "./lib/pinned.mjs";

const dir = mkdtempSync(join(tmpdir(), "geonames-"));
const zip = join(dir, "cities15000.zip");
const archive = await fetchPinned("https://download.geonames.org/export/dump/cities15000.zip");
writeFileSync(zip, archive);
const tsv = execFileSync("unzip", ["-p", zip], { maxBuffer: 64 * 1024 * 1024 }).toString("utf8");

// Columns: 0 id, 1 name, 2 asciiname, 4 lat, 5 lon, 8 country, 10 admin1, 14 population
const lines = [];
for (const row of tsv.split("\n")) {
	const c = row.split("\t");
	if (c.length < 15) continue;
	const name = (c[2] || c[1]).replace(/\|/g, " ");
	lines.push([c[8], c[10], name, Number(c[4]).toFixed(3), Number(c[5]).toFixed(3), c[14]].join("|"));
}

writeFileSync(
	new URL("../worker/data/cities.ts", import.meta.url),
	`// Generated by scripts/gen-cities.mjs from GeoNames cities15000 (CC BY 4.0, https://www.geonames.org/).
// One city per line: country|admin1|asciiname|lat|lon|population
export const CITIES_TSV = ${JSON.stringify(lines.join("\n"))};
`,
);
console.log(`wrote ${lines.length} cities`);
