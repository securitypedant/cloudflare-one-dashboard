#!/usr/bin/env node
// Generates worker/data/extraColos.ts: Cloudflare data centers listed on cloudflarestatus.com that are
// missing from speed.cloudflare.com/locations (e.g. MEX), placed at their IATA airport's coordinates
// from OurAirports (public domain). Re-run when Cloudflare adds data centers:
//   node scripts/gen-extra-colos.mjs
import { writeFileSync } from "node:fs";

const speed = await (await fetch("https://speed.cloudflare.com/locations", { headers: { referer: "https://speed.cloudflare.com/" } })).json();
const known = new Set(speed.map((l) => l.iata));

const status = await (await fetch("https://www.cloudflarestatus.com/api/v2/components.json")).json();
const missing = new Map();
for (const { name } of status.components) {
	const m = /^(.+?),\s*([^,]+?)\s*-\s*\(([A-Z]{3})\)$/.exec(name);
	if (m && !known.has(m[3])) missing.set(m[3], { city: m[1].trim() });
}

// Minimal CSV parser for quoted OurAirports rows.
const parseRow = (line) => {
	const out = [];
	let cur = "";
	let quoted = false;
	for (let i = 0; i < line.length; i++) {
		const c = line[i];
		if (quoted && c === '"' && line[i + 1] === '"') {
			cur += '"';
			i++;
		} else if (c === '"') {
			quoted = !quoted;
		} else if (c === "," && !quoted) {
			out.push(cur);
			cur = "";
		} else {
			cur += c;
		}
	}
	out.push(cur);
	return out;
};

const csv = await (await fetch("https://davidmegginson.github.io/ourairports-data/airports.csv")).text();
const [header, ...rows] = csv.trim().split("\n");
const col = Object.fromEntries(parseRow(header).map((h, i) => [h, i]));
const rank = { large_airport: 0, medium_airport: 1, small_airport: 2 };
const best = new Map();
for (const line of rows) {
	const r = parseRow(line);
	const iata = r[col.iata_code];
	if (!missing.has(iata)) continue;
	const score = rank[r[col.type]] ?? 9;
	if (!best.has(iata) || score < best.get(iata).score) {
		best.set(iata, { score, lat: Number(r[col.latitude_deg]), lon: Number(r[col.longitude_deg]), country: r[col.iso_country] });
	}
}

const colos = [...missing]
	.filter(([iata]) => best.has(iata))
	.map(([iata, { city }]) => {
		const { lat, lon, country } = best.get(iata);
		return { iata, city, country, lat: Math.round(lat * 1e4) / 1e4, lon: Math.round(lon * 1e4) / 1e4 };
	})
	.sort((a, b) => a.iata.localeCompare(b.iata));
const unresolved = [...missing.keys()].filter((k) => !best.has(k));

writeFileSync(
	new URL("../worker/data/extraColos.ts", import.meta.url),
	`// Generated by scripts/gen-extra-colos.mjs: Cloudflare data centers missing from speed.cloudflare.com/locations,
// placed at their IATA airport (OurAirports, public domain).${unresolved.length ? ` Unresolved: ${unresolved.join(", ")}.` : ""}
export const EXTRA_COLOS: { iata: string; city: string; country: string; lat: number; lon: number }[] = ${JSON.stringify(colos, null, "\t")};
`,
);
console.log(`wrote ${colos.length} extra colos${unresolved.length ? `; unresolved: ${unresolved.join(", ")}` : ""}`);
