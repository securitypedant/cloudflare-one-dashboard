#!/usr/bin/env node
// Generates shared/cni.ts from the public Direct CNI locations table:
//   https://developers.cloudflare.com/network-interconnect/locations/
// Re-run when Cloudflare updates the list:  node scripts/gen-cni.mjs
import { writeFileSync } from "node:fs";

const md = await (await fetch("https://developers.cloudflare.com/network-interconnect/locations/index.md")).text();

const sites = [];
let diverse = false;
for (const line of md.split("\n")) {
	if (line.startsWith("### Locations in diverse metros")) diverse = true;
	if (line.startsWith("### Locations in non-diverse metros")) diverse = false;
	// | **ATL** Atlanta, GA | Digital Realty ATL13 | 1 | 2 |
	const m = /^\|\s*\*\*([A-Z]{3})\*\*\s*([^|]*?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|/.exec(line);
	if (!m) continue;
	const [, metro, city, site, v1, v2] = m;
	// Diverse metros list device counts (1/2); others use ✓. "—" means not offered.
	const parse = (v) => (v === "—" || v === "-" ? 0 : v === "✓" ? 1 : Number(v) || 0);
	sites.push({ metro, city, site, v1: parse(v1), v2: parse(v2), diverse });
}
if (!sites.length) throw new Error("No CNI rows parsed; has the docs table format changed?");

writeFileSync(
	new URL("../shared/cni.ts", import.meta.url),
	`// Generated by scripts/gen-cni.mjs from https://developers.cloudflare.com/network-interconnect/locations/
// v1/v2: Direct CNI dataplane availability (in diverse metros, the number of devices; elsewhere 1 = offered).
export interface CniSite {
	metro: string;
	city: string;
	site: string;
	v1: number;
	v2: number;
	/** Metro offers device-level diversity. */
	diverse: boolean;
}

export const CNI_SITES: CniSite[] = ${JSON.stringify(sites, null, "\t")};
`,
);
console.log(`wrote ${sites.length} CNI sites in ${new Set(sites.map((s) => s.metro)).size} metros`);
